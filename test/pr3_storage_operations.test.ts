import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DurableStorage } from '../src/server/storage';
import { ScanSummaryRing, compactScanSummary, shouldWriteSummary, uploadWithBackoff, isUploadIdempotent } from '../src/server/operationalStorage';
import { payoutStatusFor } from '../src/server/payoutRegistry';
import { isEarlyClose, isCalendarSessionValid } from '../src/engine/marketCalendar';
import { validateRuntimeConfig } from '../src/server/runtimeSelfCheck';
import { uploadSummary } from '../src/server/summaryUploader';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'pr3-'));
const store = new DurableStorage(temp);
const ring = new ScanSummaryRing(200);
for (let i = 0; i < 250; i++) ring.push(compactScanSummary({ pair: 'EUR/USD', timeframe: '15m', status: i % 2 ? 'NO_TRADE' : 'CALL', reason: 'test', delivered_at: new Date(1_700_000_000_000 + i).toISOString() }));
assert.equal(ring.values().length, 200);
assert.equal(ring.values()[0].delivered_at.endsWith('.050Z'), true);
assert.equal(compactScanSummary({ pair: 'EUR/USD', timeframe: '15m', status: 'CALL', reason: 'x', delivered_at: '2026-01-01T00:00:00.000Z' }).telemetry, undefined);
assert.equal(shouldWriteSummary(49 * 1024 * 1024), true);
assert.equal(shouldWriteSummary(50 * 1024 * 1024), false);
let attempts = 0;
const upload = await uploadWithBackoff(async () => { attempts++; if (attempts < 3) throw new Error('temporary'); return 'ok'; }, { baseDelayMs: 1, maxAttempts: 3 });
assert.equal(upload.value, 'ok');
assert.equal(attempts, 3);
assert.equal(isUploadIdempotent(new Set(['summary-1']), 'summary-1'), true);
assert.equal(isUploadIdempotent(new Set(['summary-1']), 'summary-2'), false);
assert.equal((await uploadSummary({ day: '2026-01-01' }, { repositoryVisibility: 'public', upload: async () => undefined })).error, 'PUBLIC_REPOSITORY_UPLOAD_REJECTED');
assert.equal(payoutStatusFor({ pct: 90, setAt: '2026-01-01T00:00:00.000Z', source: 'TELEGRAM_MANUAL' }, Date.parse('2026-01-03T00:00:00.000Z'), 24), 'PAYOUT_STALE');
assert.equal(payoutStatusFor({ pct: 90, setAt: '2026-01-01T00:00:00.000Z', source: 'TELEGRAM_MANUAL' }, Date.parse('2026-01-01T12:00:00.000Z'), 24), 'ELIGIBLE');
assert.equal(isEarlyClose('2026-11-27T17:00:00.000Z'), true);
assert.equal(isCalendarSessionValid({ timezone: 'America/New_York', closeLocal: '13:00', earlyCloseDates: ['2026-11-27'] }), true);
assert.throws(() => validateRuntimeConfig({ NODE_ENV: 'production', SESSION_SECRET: '', DATA_DIR: temp }), /SESSION_SECRET/);
assert.doesNotThrow(() => validateRuntimeConfig({ NODE_ENV: 'production', SESSION_SECRET: '0123456789abcdef0123456789abcdef', DATA_DIR: temp }));
console.log('[pr3_storage_operations] RED/PASS contract assertions');
